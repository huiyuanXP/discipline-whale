/**
 * Report index files: one Markdown page per workspace in the whale's home.
 *
 *   1. renderReportIndex: newest first, label + [status/outcome] + bounded
 *      summary line + id per line, `count` in the header
 *   2. writeReportIndex after writeReport: the file exists and `count` equals
 *      the number of report files
 *   3. 120 reports: newest 75 lines, one omission marker, oldest 25 lines
 *   4. read_report(mode:"index") returns `returned: 'index'` and names the
 *      index file in `index.source`
 *   5. a deleted or tampered index file is rebuilt, and `index.rebuilt: true`
 *   6. ALL.md: one line per workspace with its report count and index path
 *   7. classifyReadPath judges the index file readable inside the home
 *
 * Run: node test/report-index.mjs
 */

import assert from 'node:assert/strict'
import { mkdir, mkdtemp, readFile, readdir, realpath, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

import { classifyReadPath } from '../guard.js'
import * as mainRow from '../main.js'
import {
  INDEX_MAX_LINES,
  clearStoreRoot,
  indexSummaryPath,
  readReportIndex,
  renderReportIndex,
  reportDir,
  reportIndexPath,
  setStoreRoot,
  whaleHomeDir,
  writeIndexSummary,
  writeReport,
  writeReportIndex,
} from '../store.js'

const root = await mkdtemp(join(tmpdir(), 'whale-report-index-'))
setStoreRoot(root)

const WS = { id: 'ws-blog', title: 'blog', path: '/tmp/blog', sessionIds: [] }
const BIG = { id: 'ws-big', title: 'big', path: '/tmp/big', sessionIds: [] }

/** Mount a row on a fake Host. */
function mount(row, config = {}) {
  const tools = new Map()
  const listeners = new Map()
  let seq = 0
  const ctx = {
    logger: { warn() {} },
    effect: (fn) => fn(),
    tools: { register: (definition) => { tools.set(definition.name, definition); return () => {} } },
    workspaceRegistry: { list: () => [WS, BIG] },
    sessionController: {
      create: async () => ({ sessionId: `worker-${++seq}` }),
      rename: async (request) => ({ title: request.title }),
      prompt: async (_request, signal) => { signal.throwIfAborted(); return { accepted: true } },
    },
    on: (event, handler) => { const list = listeners.get(event) ?? []; list.push(handler); listeners.set(event, list); return () => {} },
  }
  row.apply(ctx, config)
  return { tools, listeners }
}

const run = (tools, name, args, sessionId = 'main-1') =>
  tools.get(name).execute(args, { signal: new AbortController().signal, agent: { session: { id: sessionId } } })

/** A report at minute `minute` of one fixed hour, so order is by construction. */
function makeReport(workspace, index, extra = {}) {
  const minute = String(Math.floor(index / 60)).padStart(2, '0')
  const second = String(index % 60).padStart(2, '0')
  return {
    id: `r-${workspace.id}-${String(index).padStart(3, '0')}`,
    dispatchId: `dispatch-${index}`,
    workspaceId: workspace.id,
    workspaceTitle: workspace.title,
    workerSessionId: `worker-${index}`,
    mainSessionId: 'main-1',
    status: 'delivered',
    outcome: 'done',
    summary: `Report number ${index}.\nSecond line stays out of the index.`,
    document: '',
    reportedAt: `2026-10-24T06:${minute}:${second}.000Z`,
    deliveredTo: ['main-1'],
    ...extra,
  }
}

const LINE = /^- \d{4}-\d{2}-\d{2}T[\d:.]+Z \[(?:delivered|reported)\/(?:done|partial|blocked)\] .+ — r-[A-Za-z0-9_-]+$/

try {
  // 1 — the pure renderer.
  {
    const older = makeReport(WS, 1, { label: '迁移 RSS 生成器' })
    const newer = makeReport(WS, 2, { summary: `${'很长的摘要'.repeat(40)}\n第二行`, status: 'reported', revisionOf: older.id })
    const plain = makeReport(WS, 0, { summary: 'No label on this one.' })
    const text = renderReportIndex({ workspaceId: WS.id, workspaceTitle: WS.title, reports: [older, plain, newer], rebuiltAt: new Date('2026-10-24T07:00:00.000Z') })
    const lines = text.split('\n')
    assert.equal(lines[0], '# 报告索引 · blog (ws-blog)')
    assert.equal(lines[1], '<!-- generated by discipline-whale; count: 3; rebuilt: 2026-10-24T07:00:00.000Z -->')
    const body = lines.filter((line) => line.startsWith('- '))
    assert.deepEqual(body.map((line) => line.split(' — ').at(-1)), [newer.id, older.id, plain.id], 'newest first')
    for (const line of body) assert.match(line, LINE)
    assert.ok(body[1].includes('[delivered/done] 迁移 RSS 生成器 · Report number 1. — '), body[1])
    assert.ok(body[0].includes(`[reported/done] (revision of ${older.id}) `), body[0])
    const shown = body[0].split(`(revision of ${older.id}) `)[1].split(' — ')[0]
    assert.ok(shown.length <= 120 && shown.endsWith('…'), `the summary line is bounded to 120 characters (got ${shown.length})`)
    assert.ok(body[2].includes('[delivered/done] No label on this one. — '), 'without a label the summary line stands alone')
    assert.ok(!text.includes('Second line'), 'only the first summary line is indexed')
    console.log('ok 1 — renderReportIndex: newest first, label + [status/outcome] + bounded summary + id, count in the header')
  }

  // 2 — writeReport, then writeReportIndex.
  {
    for (let index = 0; index < 3; index += 1) await writeReport(root, makeReport(WS, index, { label: `task ${index}` }))
    const path = await writeReportIndex(root, WS.id, WS.title)
    assert.equal(path, reportIndexPath(root, WS.id))
    const files = (await readdir(reportDir(root, WS.id))).filter((entry) => entry.endsWith('.json'))
    const index = await readReportIndex(root, WS.id)
    assert.equal(index.count, files.length)
    assert.equal(index.text.split('\n').filter((line) => line.startsWith('- ')).length, 3)
    console.log(`ok 2 — writeReportIndex after writeReport: the file exists and count ${index.count} equals the report files`)
  }

  // 3 — the long-index split.
  {
    for (let index = 0; index < 120; index += 1) await writeReport(root, makeReport(BIG, index))
    await writeReportIndex(root, BIG.id, BIG.title)
    const { text, count } = await readReportIndex(root, BIG.id)
    assert.equal(count, 120)
    const body = text.split('\n').slice(2).filter((line) => line !== '')
    assert.equal(body.length, INDEX_MAX_LINES + 1)
    assert.equal(body[75], `… 省略 ${120 - INDEX_MAX_LINES} 份 …`)
    assert.ok(body[0].endsWith('— r-ws-big-119'), 'the newest report opens the page')
    assert.ok(body[74].endsWith('— r-ws-big-045'), 'the 75th newest closes the head')
    assert.ok(body[76].endsWith('— r-ws-big-024'), 'the tail starts at the 25th oldest')
    assert.ok(body[100].endsWith('— r-ws-big-000'), 'the oldest report closes the page')
    console.log('ok 3 — 120 reports: newest 75 lines, 「… 省略 20 份 …」, oldest 25 lines')
  }

  const { tools } = mount(mainRow)

  // 4 — the tool reads the file.
  {
    const value = await run(tools, 'read_report', { mode: 'index', workspace: 'blog' })
    assert.equal(value.returned, 'index')
    assert.equal(value.index.source, reportIndexPath(root, WS.id))
    assert.equal(value.index.rebuilt, false, 'a current file is read as it is')
    assert.equal(value.index.total, 3)
    const onDisk = (await readReportIndex(root, WS.id)).text.split('\n').filter((line) => line.startsWith('- '))
    assert.deepEqual(value.index.lines, onDisk, 'the lines are the file\'s lines')
    console.log('ok 4 — read_report(mode:"index") returns index and names the index file in index.source')
  }

  // 5 — self-healing.
  {
    await rm(reportIndexPath(root, WS.id))
    const missing = await run(tools, 'read_report', { mode: 'index', workspace: 'blog' })
    assert.equal(missing.index.rebuilt, true, 'a missing file is rebuilt')
    assert.equal(missing.index.lines.length, 3)

    await writeReport(root, makeReport(WS, 3, { label: 'task 3' }))
    const stale = await run(tools, 'read_report', { mode: 'index', workspace: 'blog' })
    assert.equal(stale.index.rebuilt, true, 'a header count behind the report folder is rebuilt')
    assert.equal(stale.index.total, 4)
    assert.ok(stale.index.lines[0].endsWith('— r-ws-blog-003'))

    const path = reportIndexPath(root, WS.id)
    await writeFile(path, (await readFile(path, 'utf8')).replace('count: 4', 'count: 9'), 'utf8')
    const tampered = await run(tools, 'read_report', { mode: 'index', workspace: 'blog' })
    assert.equal(tampered.index.rebuilt, true, 'a tampered header is rebuilt')
    assert.equal((await readReportIndex(root, WS.id)).count, 4)

    const again = await run(tools, 'read_report', { mode: 'index', workspace: 'blog' })
    assert.equal(again.index.rebuilt, false, 'a healed file is trusted on the next read')
    console.log('ok 5 — a missing, stale or tampered index file is rebuilt first and says index.rebuilt: true')
  }

  // 6 — ALL.md.
  {
    const ghost = { id: 'ws-ghost', title: 'ghost' }
    await mkdir(join(whaleHomeDir(root), 'index'), { recursive: true })
    await writeFile(reportIndexPath(root, ghost.id), renderReportIndex({ workspaceId: ghost.id, workspaceTitle: ghost.title, reports: [], rebuiltAt: new Date() }), 'utf8')
    await writeIndexSummary(root, [WS])
    const text = await readFile(indexSummaryPath(root), 'utf8')
    const lines = text.split('\n').filter((line) => line.startsWith('- '))
    assert.deepEqual(lines, [
      `- big (ws-big) · 120 份 — ${reportIndexPath(root, BIG.id)}`,
      `- blog (ws-blog) · 4 份 — ${reportIndexPath(root, WS.id)}`,
      `- ghost (ws-ghost) · 0 份 — ${reportIndexPath(root, ghost.id)}`,
    ], 'every workspace with an index file keeps its line, even when the caller names only one')
    console.log('ok 6 — ALL.md: one line per workspace with its report count and index path')
  }

  // 7 — the main session may read it.
  {
    const homeReal = await realpath(whaleHomeDir(root))
    const target = await realpath(reportIndexPath(root, WS.id))
    assert.deepEqual(classifyReadPath(target, { homeReal, workspaceRoots: [] }), { allowed: true, zone: 'home' })
    assert.equal(classifyReadPath(await realpath(indexSummaryPath(root)), { homeReal }).allowed, true)
    console.log('ok 7 — classifyReadPath judges the index files readable inside the home')
  }

  console.log('All report index checks passed.')
} finally {
  clearStoreRoot()
  await rm(root, { recursive: true, force: true })
}
