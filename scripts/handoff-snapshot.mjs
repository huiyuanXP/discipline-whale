#!/usr/bin/env node
/**
 * handoff-snapshot — regenerate the mechanically-derivable parts of
 * HANDOFF-voice-ui.md from the repository's actual state.
 *
 * The handoff document mixes two kinds of content, and only one of them can be
 * automated honestly:
 *
 *   MECHANICAL (this script) — facts that are read straight off the tree:
 *     recorded file mtimes, the changed-file list, test case counts and
 *     pass/fail, the live `.dw-*` class inventory, the call's state names, and
 *     whether the functions the UI rewrite must preserve still exist.
 *
 *   JUDGEMENT (a human or agent) — task scope, what the semantics mean, the
 *     conflict protocol, the unverified list. No generator can infer those, and
 *     a generator that guessed would be worse than no generator.
 *
 * The script rewrites ONLY the block between the SNAPSHOT markers. Everything
 * outside them is hand-written and is never touched.
 *
 * Usage:
 *   node scripts/handoff-snapshot.mjs            # update the block in place
 *   node scripts/handoff-snapshot.mjs --check    # exit 1 when the block is stale
 *   node scripts/handoff-snapshot.mjs --print    # write to stdout, touch nothing
 *
 * Exit codes: 0 ok / 1 stale (with --check) / 2 the document is missing.
 */

import { execFile } from 'node:child_process'
import { readFile, stat, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { promisify } from 'node:util'

const run = promisify(execFile)

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const DOC = join(ROOT, 'HANDOFF-voice-ui.md')
const CLIENT = join(ROOT, 'client.js')

const BEGIN = '<!-- SNAPSHOT:BEGIN (generated by scripts/handoff-snapshot.mjs — do not edit by hand) -->'
const END = '<!-- SNAPSHOT:END -->'

/** Test suites that must stay green, in the order the handoff lists them. */
const SUITES = [
  { name: 'contract', file: 'test/contract.mjs', script: 'npm test' },
  { name: 'guard', file: 'test/guard.mjs', script: 'npm run test:guard' },
  { name: 'voice', file: 'test/voice.mjs', script: 'npm run test:voice' },
  { name: 'client', file: 'test/client.mjs', script: 'npm run test:client' },
  { name: 'dock', file: 'test/dock.mjs', script: 'npm run test:dock' },
  { name: 'settings', file: 'test/settings.mjs', script: 'npm run test:settings' },
  { name: 'adhd', file: 'test/adhd.mjs', script: 'npm run test:adhd' },
  { name: 'smoke', file: 'test/smoke-restart.mjs', script: 'npm run test:smoke' },
]

/** Symbols the UI rewrite must keep alive; checked, not assumed. */
const MUST_KEEP = [
  { label: 'speakReply', pattern: /function speakReply\(/, why: '朗读 fallback 的执行体' },
  { label: 'speakable', pattern: /function speakable\(/, why: 'markdown → 可朗读文本' },
  { label: 'speechLanguage', pattern: /function speechLanguage\(/, why: '朗读语言的 BCP-47 标签' },
  { label: 'speakNote', pattern: /speakNote:/, why: '「浏览器语音合成（fallback，非真实 TTS）」文案' },
]

/** Run one command, never throwing; returns stdout regardless of exit status. */
async function capture(command, args) {
  try {
    const { stdout } = await run(command, args, { cwd: ROOT, maxBuffer: 16 * 1024 * 1024 })
    return { ok: true, out: stdout }
  } catch (error) {
    return { ok: false, out: `${error.stdout ?? ''}${error.stderr ?? ''}` }
  }
}

/** `12 minutes ago` style age, so a reader can spot a stale snapshot. */
function ageOf(mtimeMs, now) {
  const minutes = Math.max(0, Math.round((now - mtimeMs) / 60000))
  if (minutes < 1) return '刚刚'
  if (minutes < 60) return `${minutes} 分钟前`
  const hours = Math.round(minutes / 60)
  if (hours < 24) return `${hours} 小时前`
  return `${Math.round(hours / 24)} 天前`
}

/**
 * One suite's result.
 *
 * `cases` counts `ok N` lines, which the smoke script does not emit — it
 * reports a single PASS banner instead. Reporting "0 cases" for a passing suite
 * would read like a broken runner, so a suite without case lines is recorded as
 * `null` and rendered as "—（脚本式）".
 */
async function suiteResult(suite) {
  const started = Date.now()
  const result = await capture(process.execPath, [suite.file])
  const okLines = result.out.split('\n').filter((line) => /^ok /.test(line)).length
  const banner = /^(SMOKE PASS|.*checks passed\.)/m.test(result.out)
  return {
    ...suite,
    cases: okLines === 0 ? null : okLines,
    evidenced: okLines > 0 || banner,
    pass: result.ok,
    ms: Date.now() - started,
  }
}

/** Every `.dw-*` selector defined in the style block, in source order. */
function classInventory(source) {
  const styleStart = source.indexOf('function dockStyles')
  const styleEnd = source.indexOf('// ---- activation', styleStart)
  const block = source.slice(styleStart, styleEnd)
  const defined = [...block.matchAll(/\.(dw-[a-z0-9-]+)/g)].map((match) => match[1])
  // Plain and template-literal classNames; `${...}` parts are dropped, so a
  // dynamic suffix such as `dw-status-${visual}` leaves no partial name behind.
  const used = [...source.matchAll(/className: (?:"([^"]+)"|`([^`]+)`)/g)]
    .flatMap((match) => (match[1] ?? match[2].replace(/\$\{[^}]*\}/g, ' ')).split(/\s+/))
    .filter((name) => name.startsWith('dw-') && !name.endsWith('-'))
  return {
    defined: [...new Set(defined)],
    used: [...new Set(used)],
  }
}

/** The call's state names, read off the real `setPhase(...)` calls. */
function stateNames(source) {
  return [...new Set([...source.matchAll(/setPhase\("([a-z]+)"\)/g)].map((match) => match[1]))].sort()
}

/** Build the complete snapshot body (markers excluded). */
async function build() {
  const now = Date.now()
  const client = await readFile(CLIENT, 'utf8')
  const clientStat = await stat(CLIENT)
  const voiceStat = await stat(join(ROOT, 'voice.js')).catch(() => undefined)
  const silenceStat = await stat(join(ROOT, 'voice-silence.js')).catch(() => undefined)

  const [diffStat, porcelain] = await Promise.all([
    capture('git', ['diff', '--stat']),
    capture('git', ['status', '--porcelain']),
  ])

  const suites = []
  for (const suite of SUITES) suites.push(await suiteResult(suite))

  const classes = classInventory(client)
  const states = stateNames(client)
  const kept = MUST_KEEP.map((item) => ({ ...item, present: item.pattern.test(client) }))
  // Another session is rewriting client.js concurrently; this counts its
  // fingerprints so a reader can see whether that work has landed yet.
  const foreign = ['apiKey', 'baseUrl', 'pictureInPicture', 'settings', 'mute']
    .filter((token) => client.includes(token))

  const changed = porcelain.ok
    ? porcelain.out.split('\n').filter((line) => line.trim() !== '')
    : []
  const untracked = changed.filter((line) => line.startsWith('??'))
  const modified = changed.filter((line) => line.startsWith(' M'))

  // Two line lists: everything, and a comparison projection with the volatile
  // fields (wall-clock stamps, per-run durations, "N minutes ago") stripped.
  // `--check` compares the projection, so it answers "is the substance stale?"
  // instead of "did a second pass?" — which is always true.
  const lines = []
  const push = (...values) => { lines.push(...values) }

  push(
    '### 快照：仓库实际状态',
    '',
    `> 生成于 ${new Date(now).toISOString()}（本机时间 ${new Date(now).toLocaleString('zh-CN')}）。`,
    '> 本节由 `node scripts/handoff-snapshot.mjs` 重新生成；标记区间之外的内容需人工维护。',
    '',
    '**关键文件**',
    '',
    '| 文件 | 修改时间 | 距今 |',
    '| --- | --- | --- |',
    `| \`client.js\` | ${clientStat.mtime.toISOString()} | ${ageOf(clientStat.mtimeMs, now)} |`,
    voiceStat === undefined
      ? '| `voice.js` | （缺失） | — |'
      : `| \`voice.js\` | ${voiceStat.mtime.toISOString()} | ${ageOf(voiceStat.mtimeMs, now)} |`,
    silenceStat === undefined
      ? '| `voice-silence.js` | （缺失） | — |'
      : `| \`voice-silence.js\` | ${silenceStat.mtime.toISOString()} | ${ageOf(silenceStat.mtimeMs, now)} |`,
    '',
    '**测试基线**（必须是全绿；改外观后项数可能变，语义断言不应减少）',
    '',
    '| 套件 | 命令 | 用例数 | 状态 | 耗时 |',
    '| --- | --- | --- | --- | --- |',
  )
  for (const suite of suites) {
    const cases = suite.cases === null ? '—（脚本式，无逐条用例）' : suite.cases
    const status = suite.pass
      ? (suite.evidenced ? '✅ 通过' : '⚠️ 通过但无证据输出')
      : '❌ 失败'
    push(`| ${suite.name} | \`${suite.script}\` | ${cases} | ${status} | ${suite.ms} ms |`)
  }
  const total = suites.reduce((sum, suite) => sum + (suite.cases ?? 0), 0)
  const allPass = suites.every((suite) => suite.pass && suite.evidenced)
  const undefinedClasses = classes.used.filter((name) => !classes.defined.includes(name))
  push(
    '',
    `合计 **${total}** 项用例（smoke 不计条数）。整体：**${allPass ? '全绿' : '有失败'}**。`,
    '',
    '**通话条样式类（`.dw-*`）清单**',
    '',
    '| 源码里定义的类 | 渲染时用到的类 |',
    '| --- | --- |',
    `| ${classes.defined.map((name) => `\`.${name}\``).join('、') || '（无）'} | ${classes.used.map((name) => `\`${name}\``).join('、') || '（无）'} |`,
    '',
    `共定义 **${classes.defined.length}** 个、渲染使用 **${classes.used.length}** 个。`,
    undefinedClasses.length === 0
      ? '所有被渲染的类都有样式定义。'
      : `⚠️ **渲染了但没有样式定义**：${undefinedClasses.map((name) => `\`.${name}\``).join('、')}——重做外观时要么补上样式，要么删掉这个节点。`,
    '',
    '**通话状态名**（来自真实的 `setPhase(...)` 调用）',
    '',
    states.map((name) => `\`${name}\``).join('、') || '（无）',
    '',
    '**必须保留的符号（自动核对）**',
    '',
    '| 符号 | 存在 | 作用 |',
    '| --- | --- | --- |',
  )
  for (const item of kept) {
    push(`| \`${item.label}\` | ${item.present ? '✅' : '❌ **缺失**'} | ${item.why} |`)
  }
  push(
    '',
    '**并行会话指纹**（另一个会话正在改 `client.js`）',
    '',
    `检测到的对方关键字：${foreign.length === 0 ? '（暂无——它尚未落笔）' : foreign.map((token) => `\`${token}\``).join('、')}`,
    '',
    '**改动文件清单**',
    '',
    `已修改 ${modified.length} 个、未跟踪 ${untracked.length} 个。`,
    '',
    '```',
    diffStat.ok ? diffStat.out.trim() : '（git diff --stat 不可用）',
    '```',
  )

  const body = `${lines.join('\n')}\n`
  return { body, stable: stableProjection(body) }
}

/**
 * Strip the fields that legitimately change on every run, so `--check` compares
 * substance rather than clock noise.
 * @param body rendered snapshot body.
 * @returns the same text with timestamps, ages and durations masked.
 */
function stableProjection(body) {
  return body
    .replace(/^> 生成于 .*$/gm, '> 生成于 <stamp>')
    .replace(/^\| \`[^`]+\` \| \d{4}-\d\d-\d\dT[\d:.]+Z \| .* \|$/gm,
      (line) => line.replace(/\| \d{4}-\d\d-\d\dT[\d:.]+Z \| .* \|$/, '| <mtime> | <age> |'))
    .replace(/^\| (contract|guard|voice|client|dock|settings|adhd|smoke) \| (.+) \| (\d+|—[^|]*) \| (.+) \| \d+ ms \|$/gm,
      '| $1 | $2 | $3 | $4 | <ms> |')
}

/** Replace the marked block in `document`, or fail loudly when markers are gone. */
function splice(document, body) {
  const begin = document.indexOf(BEGIN)
  // Search for END *after* BEGIN: the prose above may quote the markers while
  // explaining them, and a bare `indexOf(END)` would match that quotation.
  const end = begin < 0 ? -1 : document.indexOf(END, begin + BEGIN.length)
  if (begin < 0 || end < 0) {
    throw new Error(`找不到快照标记；文档应包含：\n${BEGIN}\n${END}`)
  }
  return `${document.slice(0, begin + BEGIN.length)}\n\n${body}\n${document.slice(end)}`
}

const flags = new Set(process.argv.slice(2))
const snapshot = await build()

if (flags.has('--print')) {
  process.stdout.write(snapshot.body)
  process.exit(0)
}

let document
try {
  document = await readFile(DOC, 'utf8')
} catch {
  console.error(`找不到交接文档：${DOC}`)
  process.exit(2)
}

const next = splice(document, snapshot.body)
if (flags.has('--check')) {
  // Compare the SUBSTANCE, not the rendered text: the stored block still holds
  // the previous run's timestamps and durations, which always differ.
  const stored = document.slice(
    document.indexOf(BEGIN) + BEGIN.length,
    document.indexOf(END, document.indexOf(BEGIN) + BEGIN.length),
  )
  // Trim both sides: `splice` frames the body with blank lines, and the stored
  // slice carries them while the generated `body` does not.
  const stale = stableProjection(stored).trim() !== snapshot.stable.trim()
  console.log(stale ? 'snapshot STALE — 运行 node scripts/handoff-snapshot.mjs 更新' : 'snapshot fresh')
  process.exit(stale ? 1 : 0)
}

await writeFile(DOC, next, 'utf8')
console.log('snapshot updated in HANDOFF-voice-ui.md')
